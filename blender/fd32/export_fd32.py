"""Export the FD-32 .blend to FBX for Unity and write the parts table (copy of blender/nimrod/export_nimrod.py, root FD32_root).

  blender --background assets/model_nimrod/nimrod.blend --python blender/nimrod/export_nimrod.py -- --fbx assets/model_nimrod/nimrod.fbx --table assets/model_nimrod/nimrod_parts
      --fbx assets/model_v2/b25h_v2.fbx --table assets/model_v2/b25h_v2_parts

Axis conversion. Blender model: nose +Y, up +Z, right wing +X. Unity's FBX importer turns the
right-handed Y-up FBX scene into its left-handed frame by negating X. We write the data already
in FBX Y-up space with the proper rotation M: Blender (x, y, z) -> FBX (-x, z, y) (det +1, no
winding flip), which Unity reads as (x, z, y): nose +Z, up +Y, right wing +X.
The CG root (FD32_root) is moved to the origin (all objects translated by -CG) before conversion.
M is applied to every mesh and conjugated into every object matrix (M W M^-1); the FBX is then
written with use_space_transform=False (file declares Y up / -Z forward and nothing is rotated), so
no object - the root included - carries a 90 deg correction. Units: metres, apply_scale_options
FBX_SCALE_ALL, scale 1.0. (Blender 5.2's experimental bake_space_transform gave wrong child
transforms for nested hierarchies on re-import, so it is not used.) The .blend is not modified.
"""
import bpy, sys, os, json, math
from mathutils import Vector, Matrix, Quaternion

argv = sys.argv[sys.argv.index('--') + 1:] if '--' in sys.argv else []
fbx = os.path.abspath(argv[argv.index('--fbx') + 1])
table = os.path.abspath(argv[argv.index('--table') + 1]) if '--table' in argv else None
os.makedirs(os.path.dirname(fbx), exist_ok=True)


C = bpy.data.objects['FD32_root'].matrix_world.translation.copy()   # CG -> becomes the FBX/Unity origin


def u(v):            # Blender world vector -> Unity (x right, y up, z forward)
    return (round(v[0], 4), round(v[2], 4), round(v[1], 4))


def up(v):           # Blender world POSITION -> Unity position relative to the CG root
    return u(Vector(v) - C)


def write_table(path):
    rows = []
    for o in sorted(bpy.data.objects, key=lambda o: o.name):
        if o.type not in ('MESH', 'EMPTY'):
            continue
        info = json.loads(o['b25_info']) if o.get('b25_info') else {}
        mw = o.matrix_world
        row = dict(name=o.name, parent=o.parent.name if o.parent else None, type=o.type,
                   pivot_unity=up(mw.translation),
                   tris=(sum(len(p.vertices) - 2 for p in o.data.polygons) if o.type == 'MESH' else 0))
        R = mw.to_3x3().normalized()
        row['local_axes_unity'] = dict(x=u(R.col[0]), y=u(R.col[2]), z=u(R.col[1]))
        for k in ('hinge_axis', 'hinge_axis_world'):
            if k in info:
                info[k + '_unity'] = u(info[k])
        if 'retract_deg_blender' in info:
            info['retract_unity'] = (f"localRotation = Quaternion.AngleAxis({-info['retract_deg_blender']:.1f}f, Vector3.right) "
                                     "(from the extended pose, identity)")
        if 'open_deg' in info and 'hinge_axis' in info:
            info['open_unity'] = (f"rotate {-info['open_deg']:.1f} deg (Unity AngleAxis) about {u(info['hinge_axis'])} "
                                  "(parent space) from the CLOSED pose")
        row['info'] = info
        rows.append(row)
    with open(path + '.json', 'w') as f:
        json.dump(rows, f, indent=1)
    with open(path + '.md', 'w') as f:
        f.write('# FD-32 parts table (generated by blender/fd32/export_fd32.py)\n\n')
        f.write('Unity coordinates: x right, y up, z forward (nose). Pivot = object origin in model space '
                'relative to FD32_root = the CG, which is the FBX origin (gear down). Unity collapses the single FBX root '
                'node into the prefab root, so the prefab root IS FD32_root. Rotation rule: a Blender rotation of +a deg about '
                'axis (x, y, z) is Unity `Quaternion.AngleAxis(-a, new Vector3(x, z, y))`.\n\n')
        f.write('| object | parent | pivot (x, y, z) | local X / Y / Z axes | tris | notes |\n|---|---|---|---|---|---|\n')
        for r in rows:
            ax = r['local_axes_unity']
            axes = f"{ax['x']} / {ax['y']} / {ax['z']}" if any(abs(a - b) > 1e-3 for a, b in zip(ax['x'] + ax['y'] + ax['z'], (1, 0, 0, 0, 1, 0, 0, 0, 1))) else 'identity'
            notes = '; '.join(f'{k}={v}' for k, v in r['info'].items())
            f.write(f"| {r['name']} | {r['parent']} | {r['pivot_unity']} | {axes} | {r['tris']} | {notes} |\n")
    print('[export] table', path + '.md')


if table:
    write_table(table)

# ---- convert the scene (in memory only) into FBX Y-up space
M3 = Matrix(((-1, 0, 0), (0, 0, 1), (0, 1, 0)))
M = M3.to_4x4()
Mi = M.inverted()
objs = [o for o in bpy.data.objects if o.type in ('MESH', 'EMPTY')]
EXTRAS = {o.name for o in objs if o.users_collection and o.users_collection[0].name == 'FD32_extras'}
world = {o.name: o.matrix_world.copy() for o in objs}
for me in {o.data for o in objs if o.type == 'MESH'}:
    me.transform(M)
    me.update()


def depth(o):
    d = 0
    while o.parent:
        d += 1
        o = o.parent
    return d


for o in sorted(objs, key=depth):
    o.matrix_parent_inverse = Matrix.Identity(4)
    o.matrix_world = (M @ world[o.name] @ Mi) if o.name in EXTRAS else (M @ Matrix.Translation(-C) @ world[o.name] @ Mi)
    bpy.context.view_layer.update()
for o in bpy.context.view_layer.objects:
    o.select_set(o.type in ('MESH', 'EMPTY') and o.name not in EXTRAS)
bpy.ops.export_scene.fbx(
    filepath=fbx, use_selection=True, object_types={'MESH', 'EMPTY'},
    apply_unit_scale=True, apply_scale_options='FBX_SCALE_ALL', global_scale=1.0,
    axis_forward='-Z', axis_up='Y', use_space_transform=False, bake_space_transform=False,
    mesh_smooth_type='FACE', use_mesh_modifiers=True, use_tspace=False,
    use_custom_props=False, add_leaf_bones=False, bake_anim=False,
    path_mode='AUTO', embed_textures=False)
print('[export] wrote', fbx, os.path.getsize(fbx), 'bytes')
if EXTRAS:
    # prop blur meshes: their own small FBX (hub frame, Unity +Z = spin axis), never shown unwired in the main model
    xf = fbx[:-4] + '_propdisc.fbx'
    for o in bpy.context.view_layer.objects:
        o.select_set(o.name in EXTRAS)
    bpy.ops.export_scene.fbx(
        filepath=xf, use_selection=True, object_types={'MESH'}, apply_unit_scale=True, apply_scale_options='FBX_SCALE_ALL',
        global_scale=1.0, axis_forward='-Z', axis_up='Y', use_space_transform=False, bake_space_transform=False,
        mesh_smooth_type='FACE', use_tspace=False, use_custom_props=False, add_leaf_bones=False, bake_anim=False)
    print('[export] wrote', xf, os.path.getsize(xf), 'bytes')
