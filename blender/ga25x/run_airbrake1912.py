"""1.9.12: build, export and check the GA-25X airbrake add-on from the SHIPPED model (which is only read).

  python blender/ga25x/run_airbrake1912.py [--out <dir>] [--renders <dir>] [--skip-renders]

Steps: airbrake1912.py on assets/model_ga25x/ga25x.blend -> <out>/ga25x_airbrake.blend + .json  ->  the project's own FBX exporter
(blender/v2/export_b25h_v2.py, the GA-25X variant that run_ga25x.py makes) -> <out>/ga25x_airbrake.fbx + ga25x_airbrake_parts.md/.json
->  check_airbrake1912.py (both FBX re-imported) -> <out>/ga25x_airbrake_check.json  ->  site_scan1912.py (the faction mark of every
livery read from its texture: no mark-colour texel may lie under the built panel; the numbers of the rejected sites) ->
<out>/ga25x_airbrake_site.json  ->  renders (every livery, shut / open, lit / flat, both sides and straight behind)
into --renders (default: ../nuclearoption-ref/study/v1912/ga25x_airbrake/renders_airbrake1912_r2, outside the repo). Default <out> = assets/model_ga25x. The main model files are not written; their hashes are compared
before and after.
"""
import os, sys, subprocess, tempfile, hashlib, json
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import run_ga25x as RG

ROOT, V2, BLENDER = RG.ROOT, RG.V2, RG.BLENDER
MODEL = os.path.join(ROOT, 'assets', 'model_ga25x')
TEX = os.path.join(ROOT, 'assets', 'textures_ga25x')


def sha(p):
    return hashlib.sha256(open(p, 'rb').read()).hexdigest()[:12]


def bl(args):
    print('>>', ' '.join(os.path.basename(a) for a in args[:5]), '...', flush=True)
    r = subprocess.run([BLENDER, '--background', '--python-exit-code', '1'] + args)
    if r.returncode:
        sys.exit(f'step failed: {args}')


def sheets(rdir):
    from PIL import Image
    tiles = json.load(open(os.path.join(rdir, 'tiles.json')))
    for k, fs in tiles.items():
        ims = [Image.open(f).convert('RGB') for f in fs]
        w, h = ims[0].size
        n = 5
        sheet = Image.new('RGB', (w * n, h * ((len(ims) + n - 1) // n)))
        for i, im in enumerate(ims):
            sheet.paste(im, ((i % n) * w, (i // n) * h))
        sheet.save(os.path.join(rdir, f'sheet_{k}.jpg'), quality=88)
    print('[airbrake] contact sheets', len(tiles))


def main():
    out = os.path.abspath(sys.argv[sys.argv.index('--out') + 1]) if '--out' in sys.argv else MODEL
    os.makedirs(out, exist_ok=True)
    blend, fbx = os.path.join(MODEL, 'ga25x.blend'), os.path.join(MODEL, 'ga25x.fbx')
    before = (sha(blend), sha(fbx))
    tmp = tempfile.mkdtemp(prefix='ga25x_airbrake_')
    exp = RG.variant(os.path.join(V2, 'export_b25h_v2.py'), os.path.join(tmp, 'export_ga25x_airbrake.py'),
                     [("objects['B25H_root']", "objects['GA25X_root']"), ("== 'B25H_extras'", "== 'GA25X_extras'"),
                      ('# B-25H v2 parts table (generated by blender/v2/export_b25h_v2.py)',
                       '# GA-25X airbrake add-on parts table (generated by blender/ga25x/run_airbrake1912.py from blender/v2/export_b25h_v2.py)'),
                      ('relative to B25H_root', 'relative to GA25X_root'), ('prefab root IS B25H_root', 'prefab root IS GA25X_root')])
    bl([blend, '--python', os.path.join(HERE, 'airbrake1912.py'), '--', '--out', out])
    ab = os.path.join(out, 'ga25x_airbrake.blend')
    bl([ab, '--python', exp, '--', '--fbx', os.path.join(out, 'ga25x_airbrake.fbx'), '--table', os.path.join(out, 'ga25x_airbrake_parts')])
    bl(['--factory-startup', '--python', os.path.join(HERE, 'check_airbrake1912.py'), '--', fbx, os.path.join(out, 'ga25x_airbrake.fbx'),
        os.path.join(out, 'ga25x_airbrake.json'), os.path.join(out, 'ga25x_airbrake_check.json')])
    site = os.path.join(out, 'ga25x_airbrake_site.json')
    bl([blend, '--python', os.path.join(HERE, 'site_scan1912.py'), '--', TEX, site])
    sj = json.load(open(site))
    built = [v for k, v in sj['sites'].items() if '(BUILT)' in k]
    if len(built) != 1 or any(built[0]['mark_colour_samples'].values()) or any(built[0]['composer_box_overlap'].values()):
        sys.exit(f'site scan: the built panel is not clear of the faction marks: {built}')
    print('[airbrake] site scan: built site', built[0]['area_m2'], 'm2 per side =', built[0]['share_of_first'], 'of the first build; mark-colour texels under it', built[0]['mark_colour_samples'])
    if (sha(blend), sha(fbx)) != before:
        sys.exit('the main model files changed during the run')
    print('[airbrake] main model untouched: ga25x.blend', before[0], 'ga25x.fbx', before[1])
    print('[airbrake] ga25x_airbrake.fbx', sha(os.path.join(out, 'ga25x_airbrake.fbx')), os.path.getsize(os.path.join(out, 'ga25x_airbrake.fbx')), 'bytes')
    if '--skip-renders' in sys.argv:
        return
    # renders stay out of the repo (about 70 MB): default = the reference folder beside the repo
    rdir = os.path.abspath(sys.argv[sys.argv.index('--renders') + 1]) if '--renders' in sys.argv else os.path.join(
        os.path.dirname(ROOT), 'nuclearoption-ref', 'study', 'v1912', 'ga25x_airbrake', 'renders_airbrake1912_r2')
    bl([blend, '--python', os.path.join(HERE, 'render_airbrake1912.py'), '--', TEX, rdir])
    sheets(rdir)


if __name__ == '__main__':
    main()
