def run(args):
    print('>>', ' '.join(os.path.basename(a) for a in args[:6]), '...', flush=True)
    r = subprocess.run([BLENDER, '--background', '--python-exit-code', '1'] + args)
    if r.returncode:
        sys.exit(f'step failed: {args}')


def variant(src, dst, subs, required=None):
    s = open(src, encoding='utf-8').read()
    if required is not None:
        a = s.index('REQUIRED = ([')
        b = s.index('MATS = {')
        s = s[:a] + required + s[b:]
    for old, new in subs:
        if old not in s:
            sys.exit(f'variant {os.path.basename(src)}: pattern not found: {old!r}')
        s = s.replace(old, new)
    open(dst, 'w', encoding='utf-8').write(s)
    return dst


