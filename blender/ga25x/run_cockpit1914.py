"""1.9.14: GA-25X cockpit art fix on the SHIPPED model (only cockpit_interior changes; the livery atlas stays as shipped).

  python blender/ga25x/run_cockpit1914.py <fresh build dir with ga25x.blend> [--out <dir inside assets/>]

Steps: patch_cockpit1914.py (shipped blend + fresh cockpit_interior) -> <out>/ga25x.blend -> the GA-25X FBX export (run_ga25x
variant) -> check (incl. the 1.8.16 livery-atlas guard: must PASS, i.e. no part moved) -> contract -> v030 check -> stores check
-> round 4 control / visibility measurement (check_ck_align1914.py -> ga25x_ck_align.json) -> round 7 throttle sweep
(check_throttle_clear1914.py -> ga25x_throttle_clear.json) -> stub test.
The fresh build dir: blender --background --factory-startup --python blender/ga25x/build_ga25x.py -- --out <dir>/ga25x.blend
<out> must sit two levels under the repo (assets/<dir>): the check finds the repo from the FBX folder. Default out =
assets/model_ga25x (the shipped folder; the files it writes are replaced).
"""
import os, sys, subprocess, tempfile, shutil
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import run_ga25x as RG

MODEL = os.path.join(RG.ROOT, 'assets', 'model_ga25x')


def main():
    fresh = os.path.abspath(sys.argv[1])
    out = os.path.abspath(sys.argv[sys.argv.index('--out') + 1]) if '--out' in sys.argv else MODEL
    os.makedirs(out, exist_ok=True)
    tmp = tempfile.mkdtemp(prefix='ga25x_ck1914_')
    shipped = os.path.join(tmp, 'shipped.blend')
    shutil.copy2(os.path.join(MODEL, 'ga25x.blend'), shipped)
    blend, fbx = os.path.join(out, 'ga25x.blend'), os.path.join(out, 'ga25x.fbx')
    exp = RG.variant(os.path.join(RG.V2, 'export_b25h_v2.py'), os.path.join(tmp, 'export_ga25x.py'),
                     [("objects['B25H_root']", "objects['GA25X_root']"), ("== 'B25H_extras'", "== 'GA25X_extras'"),
                      ('# B-25H v2 parts table (generated by blender/v2/export_b25h_v2.py)',
                       '# GA-25X parts table (generated by blender/ga25x/run_ga25x.py from blender/v2/export_b25h_v2.py)'),
                      ('relative to B25H_root', 'relative to GA25X_root'), ('prefab root IS B25H_root', 'prefab root IS GA25X_root')])
    chk = RG.variant(os.path.join(RG.V2, 'check_b25h_v2.py'), os.path.join(tmp, 'check_ga25x.py'),
                     [("O.get('B25H_root')", "O.get('GA25X_root')"), ("'muzzle_tail_L'", "'mws_tail'"),
                      ("for k in (1, 2, 3):", "for k in range(1, 7):"),
                      ("'prop', 'prop_tip', 'cockpit', 'gauges', 'screen'}", "'prop', 'cockpit', 'gauges', 'screen', 'sensor', 'light_off', 'ck_struct', 'ck_panel', 'ck_black', 'ck_art', 'ck_throttle'}")],
                     required=RG.GA_REQUIRED)
    shutil.copy2(os.path.join(RG.V2, 'b25h_spec.py'), tmp)   # the check loads it from its own folder (1.8.14 roof section)
    RG.run([shipped, '--python', os.path.join(HERE, 'patch_cockpit1914.py'), '--', os.path.join(fresh, 'ga25x.blend'), blend])
    RG.run([blend, '--python', exp, '--', '--fbx', fbx, '--table', os.path.join(out, 'ga25x_parts')])
    # the B-25H check run on the GA-25X: three 1.8.14 B-25H-only rows (dorsal turret opening, torn-seam lap strips) fail on the
    # SHIPPED GA-25X FBX as well; every other row, the livery-atlas guard included, must pass
    KNOWN = ('1.8.14 roof skin round the dorsal opening', '1.8.14 torn fuselage seams', '1.8.14 lap strips stay under the skin')
    r = subprocess.run([RG.BLENDER, '--background', '--python-exit-code', '1', '--factory-startup', '--python', chk, '--', fbx,
                        '--json', os.path.join(out, 'ga25x_check.json')], capture_output=True, text=True, errors='replace')
    fails = [l for l in r.stdout.splitlines() if l.startswith('FAIL ')]
    npass = sum(l.startswith('PASS ') for l in r.stdout.splitlines())
    other = [l for l in fails if not l[5:].startswith(KNOWN)]
    print(f'[cockpit1914] check: {npass} PASS, {len(fails)} FAIL ({len(fails) - len(other)} known B-25H-only)')
    if other or npass < 30 or 'Traceback' in r.stdout + r.stderr and not fails:
        sys.exit('check failed:\n' + '\n'.join(other) + r.stderr[-2000:])
    RG.run([blend, '--python', os.path.join(HERE, 'contract_ga25x.py'), '--', '--out', os.path.join(out, 'ga25x_contract')])
    RG.run([blend, '--python', os.path.join(HERE, 'check_v030_ga25x.py'), '--', os.path.join(out, 'ga25x_v030_check.json')])
    RG.run([blend, '--python', os.path.join(HERE, 'check_stores_ga25x.py'), '--', os.path.join(out, 'ga25x_stores_check.json')])
    # round 4: modelled controls vs painted ones and art visibility from the crew eyes, measured on the patched mesh
    # (tools/stub_tests_1914.py reads ga25x_ck_align.json)
    RG.run([blend, '--python', os.path.join(HERE, 'check_ck_align1914.py'), '--', os.path.join(out, 'ga25x_ck_align.json')])
    # round 7: throttle lever swept through its game travel (Cockpit.Throttle, 0..52 deg) vs the radio panel / pedestal / panel
    RG.run([blend, '--python', os.path.join(HERE, 'check_throttle_clear1914.py'), '--', os.path.join(out, 'ga25x_throttle_clear.json')])
    r = subprocess.run([sys.executable, os.path.join(HERE, 'test_ga25x_stub.py'), out])
    if r.returncode:
        sys.exit('GA-25X stub test failed')
    print('[cockpit1914] done ->', out)


if __name__ == '__main__':
    main()
