"""Export the MSB-17/80 .blend to FBX for Unity + the parts table: the B-17G exporter (blender/b17g/export_b17g.py) run with the MSB root
names (MSB17_root / MSB17_extras; MSB1780_* until 1.9.9); the B-17G file is read, never changed.

  blender --background assets/model_msb1780/msb1780.blend --python-exit-code 1 --python blender/msb1780/export_msb1780.py -- \
      --fbx assets/model_msb1780/msb1780.fbx --table assets/model_msb1780/msb1780_parts
"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(HERE, '..', 'b17g', 'export_b17g.py'), encoding='utf-8').read()
for a, b in (("'B17G_root'", "'MSB17_root'"), ("'B17G_extras'", "'MSB17_extras'"), ('# B-17G parts table (generated by blender/b17g/export_b17g.py)',
             '# MSB-17 parts table (generated by blender/msb1780/export_msb1780.py from the B-17G exporter)'), ('relative to B17G_root', 'relative to MSB17_root'),
             ('the prefab root IS B17G_root', 'the prefab root IS MSB17_root')):
    assert a in src, a
    src = src.replace(a, b)
exec(compile(src, os.path.join(HERE, 'export_msb1780 (export_b17g.py)'), 'exec'), {'__name__': '__main__', '__file__': __file__})
